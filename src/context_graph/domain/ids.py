"""Deterministic identity and normalization helpers.

Deterministic identity protects against *exact* duplicates only; semantic
equivalence is handled by embedding-based resolution (spec section 3). System
identity is never generated by the LLM.
"""

from __future__ import annotations

import json
import re
import uuid
from hashlib import blake2b
from typing import Any

_WHITESPACE = re.compile(r"\s+")
_NON_WORD = re.compile(r"[^a-z0-9]+")

_ID_DIGEST_BYTES = 12


def new_id(prefix: str) -> str:
    """Generate a fresh system identity (``context_id``, ``concept_id``, ...)."""
    return f"{prefix}_{uuid.uuid4().hex}"


def deterministic_id(prefix: str, *parts: str) -> str:
    """Stable identity derived from ``parts``; identical inputs give one id."""
    digest = blake2b("\x1f".join(parts).encode("utf-8"), digest_size=_ID_DIGEST_BYTES)
    return f"{prefix}_{digest.hexdigest()}"


def normalize_text(text: str) -> str:
    """Case-fold and collapse whitespace for stable comparison."""
    return _WHITESPACE.sub(" ", text.strip()).casefold()


def slugify(text: str) -> str:
    """Normalize a concept name into a stable snake_case key."""
    return _NON_WORD.sub("_", normalize_text(text)).strip("_")


def canonical_value(value: Any) -> str:
    """Canonical string form of a context value, used for equality and hashing."""
    if isinstance(value, str):
        return normalize_text(value)
    return json.dumps(value, sort_keys=True, separators=(",", ":"), default=str)


def concept_key(namespace: str, concept: str) -> str:
    """Deterministic key for a reusable semantic concept."""
    return f"{slugify(namespace)}:{slugify(concept)}"


def context_fingerprint(
    *,
    subject_user_id: str,
    scope_type: str,
    scope_id: str,
    concept_id: str,
    value: Any,
) -> str:
    """Exact-duplicate fingerprint for a scoped context value.

    Concurrent workers MERGE on this fingerprint, so the same value in the same
    scope can never produce two canonical instances.
    """
    return deterministic_id(
        "fp",
        subject_user_id,
        scope_type,
        scope_id,
        concept_id,
        canonical_value(value),
    )
